"""Named configuration spans shared by branch generation and session retention."""
from pathlib import Path
import json
import re
from project_paths import PROJECT_ROOT, SOURCE_ROOT
def layout():
    value=json.loads((SOURCE_ROOT/'model/RuntimeLayout2026.json').read_text(encoding='utf-8'))
    end=0;names=set()
    for row in sorted(value['configuration']+value.get('lifecycle',[]),key=lambda r:r['offset']):
        if not re.fullmatch(r'[A-Z][A-Za-z0-9]+',row['name']) or row['name'] in names:
            raise ValueError('Invalid/duplicate runtime field name')
        if row['offset']<end or row['size']<=0 or row['offset']+row['size']>value['state_size']:
            raise ValueError('Overlapping/out-of-bounds runtime span')
        if not row['evidence']: raise ValueError('Runtime field needs evidence')
        names.add(row['name']);end=row['offset']+row['size']
    for row in value.get('lifecycle',[]):
        if row['retention'] not in ('preserve','reset','baseline'): raise ValueError('Invalid lifecycle retention')
    return value

def header():
    value=layout()
    lines=['// Generated by recover_runtime.py from model/RuntimeLayout2026.json.',
        '#pragma once','#include <cstddef>','namespace san9::layout2026 {',
        f'inline constexpr std::size_t StateSize = {value["state_size"]};',
        'struct Span { std::size_t offset, size; };']
    for row in value['configuration']+value.get('lifecycle',[]):
        lines.extend([f'// Evidence: {row["evidence"]}',
            f'inline constexpr std::size_t {row["name"]} = {row["offset"]};',
            f'inline constexpr std::size_t {row["name"]}Size = {row["size"]};'])
    lines.append('inline constexpr Span ConfigurationSpans[] = {')
    for row in value['configuration']: lines.append(f'    {{{row["name"]}, {row["name"]}Size}},')
    lines.append('};')
    for policy in ('preserve','reset'):
        lines.append(f'inline constexpr Span Lifecycle{policy.title()}Spans[] = {{')
        for row in value.get('lifecycle',[]):
            if row['retention']==policy: lines.append(f'    {{{row["name"]}, {row["name"]}Size}},')
        lines.append('};')
    lines.extend(['} // namespace san9::layout2026',''])
    return '\n'.join(lines)

def name_state_offsets(text):
    value=layout()
    names={str(row['offset']):row['name'] for row in value['configuration']+value.get('lifecycle',[])}
    return re.sub(r'\bstate \+ (\d+)\b',lambda m:'state + san9::layout2026::'+names[m[1]] if m[1] in names else m[0],text)
