"""Apply reviewed semantic names to fixed injection data and evidence views.

The catalog links legacy identifiers to recovered offsets/operands. Renaming is
lexical: string literals, types, widths, pointer views and control flow stay intact.
"""
from pathlib import Path
import json
import re

from project_paths import PROJECT_ROOT, SOURCE_ROOT
TOKENS = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|\b[A-Za-z_]\w*\b', re.S)
PROTECTED = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', re.S)


def catalog():
    value = json.loads((SOURCE_ROOT / 'model/InjectionNames2026.json').read_text(encoding='utf-8'))
    for rows in (value['fields'].values(), value['symbols'].values()):
        names = [row['name'] for row in rows]
        if len(names) != len(set(names)) or any(not re.fullmatch(r'[A-Za-z_]\w*', n) for n in names):
            raise ValueError('Invalid or duplicate injection name')
    for names in (*value['locals'].values(), value['labels']):
        if len(names.values()) != len(set(names.values())):
            raise ValueError('Duplicate local injection name')
    return value


def rename_tokens(text, names):
    return TOKENS.sub(lambda m: names.get(m[0], m[0]), text)


def header():
    lines = ['// Generated by recover_runtime.py. Edit model/InjectionNames2026.json.',
             '#pragma once', '#include <cstddef>', 'namespace san9::injection2026 {']
    for offset, row in catalog()['fields'].items():
        lines.append('// ' + row['evidence'] + ('; legacy: ' + row['legacy'] if row['legacy'] else ''))
        lines.append(f'inline constexpr std::size_t {row["name"]} = {offset};')
    lines.extend(['} // namespace san9::injection2026', ''])
    return '\n'.join(lines)


def name_symbols(text):
    return rename_tokens(text, {old: row['name'] for old, row in catalog()['symbols'].items()})


def name_fields(text):
    fields = catalog()['fields']
    def offset(match):
        return 'san9::injection2026::' + fields[match[1]]['name'] if match[1] in fields else match[1]
    def code(fragment):
        fragment = re.sub(r'(?<=state \+ )(\d+)\b', offset, fragment)
        return re.sub(r'(?<=field<DWORD>\()(\d+)\b', offset, fragment)
    result = []
    start = 0
    for protected in PROTECTED.finditer(text):
        result.extend((code(text[start:protected.start()]), protected[0]))
        start = protected.end()
    result.append(code(text[start:]))
    return ''.join(result)


def original_names(text, va):
    """Undo presentation changes for structural regression and evidence review."""
    value = catalog()
    text = re.sub(r'san9::injection2026::(\w+)',
                  lambda m: next(o for o, row in value['fields'].items() if row['name'] == m[1]), text)
    names = {row['name']: old for old, row in value['symbols'].items()}
    names.update({new: old for old, new in value['locals'][va].items()})
    if va == '409E10':
        names.update({new: old for old, new in value['labels'].items()})
    return rename_tokens(text, names)
